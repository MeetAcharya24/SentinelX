"""Synthetic network flows for demo mode: `python -m app.ml.demo_flows`.

Every value is drawn from the hand-written profiles below, which are loosely
shaped like kinds of traffic described in UNSW-NB15. No dataset row is copied,
and the output is labelled as demo data so it is never mistaken for captured
traffic.
"""

import argparse
