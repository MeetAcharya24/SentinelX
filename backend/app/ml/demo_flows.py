from app.ml.schema import FEATURE_COLUMNS

# One scoring request takes at most this many flows.
MAX_DEMO_FLOWS = 100
DEFAULT_COUNT = 20
DEFAULT_SEED = 1

DEMO_NOTICE = (
    "Synthetic demo data generated by SentinelX. These flows were not captured from any network."
)

_DECIMALS = 6
_TCP = "tcp"
_TCP_WINDOW = 255
_TCP_SEQUENCE_LIMIT = 2**32
# Roughly one packet in four is counted as retransmitted or dropped.
_PACKETS_PER_LOSS = 4
# Share of the connection set-up time spent waiting for the SYN-ACK.
_SYNACK_SHARE = (0.5, 0.8)
# Jitter as a multiple of the mean gap between packets.
_SOURCE_JITTER_FACTOR = (30.0, 90.0)
_DEST_JITTER_FACTOR = (3.0, 40.0)
# Share of the response bytes that are HTTP body rather than headers.
_HTTP_BODY_SHARE = (0.3, 0.5)

Range = tuple[float, float]


@dataclass(frozen=True)
class Profile:
    """A kind of traffic and the ranges its flows are drawn from."""

    name: str
    description: str
    proto: str
    service: str
    state: str
    duration_s: Range
    source_packets: Range
    dest_packets: Range
    source_packet_bytes: Range
    dest_packet_bytes: Range
    source_ttl: int
    dest_ttl: int
    ct_state_ttl: int
    # How many other recent connections share this flow's source, destination or service.
    recent_connections: Range
    # How many of them also share a port.
    same_port_connections: Range
    # TCP only: time taken to set up the connection.
    handshake_s: Range | None = None
    is_http: bool = False


@dataclass(frozen=True)
class DemoFlow:
    profile: str
    features: dict[str, Any]


