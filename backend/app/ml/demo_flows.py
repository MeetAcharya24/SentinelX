def _whole(rng: np.random.Generator, bounds: Range) -> int:
    return int(rng.integers(int(bounds[0]), int(bounds[1]) + 1))


def _between(rng: np.random.Generator, bounds: Range) -> float:
    return float(rng.uniform(bounds[0], bounds[1]))


def _log_between(rng: np.random.Generator, bounds: Range) -> float:
    """Spreads draws evenly across orders of magnitude."""
    return math.exp(_between(rng, (math.log(bounds[0]), math.log(bounds[1]))))


def _direction_fields(packets: int, packet_bytes: int, duration: float) -> tuple[float, float]:
    """Load in bits per second and mean gap between packets in milliseconds."""
    if packets < 2:
        return 0.0, 0.0
    total_bytes = packets * packet_bytes
    load = 8 * total_bytes * (packets - 1) / packets / duration
    return load, duration * 1000 / (packets - 1)


def _volume_fields(profile: Profile, rng: np.random.Generator) -> dict[str, Any]:
    duration = round(_log_between(rng, profile.duration_s), _DECIMALS)
    source_packets = _whole(rng, profile.source_packets)
    dest_packets = _whole(rng, profile.dest_packets)
    source_packet_bytes = _whole(rng, profile.source_packet_bytes)
    dest_packet_bytes = _whole(rng, profile.dest_packet_bytes) if dest_packets else 0
    source_load, source_gap = _direction_fields(source_packets, source_packet_bytes, duration)
    dest_load, dest_gap = _direction_fields(dest_packets, dest_packet_bytes, duration)
    return {
        "dur": duration,
        "spkts": source_packets,
        "dpkts": dest_packets,
        "sbytes": source_packets * source_packet_bytes,
        "dbytes": dest_packets * dest_packet_bytes,
        "rate": (source_packets + dest_packets - 1) / duration,
        "sload": source_load,
        "dload": dest_load,
        "sinpkt": source_gap,
        "dinpkt": dest_gap,
        "smean": source_packet_bytes,
        "dmean": dest_packet_bytes,
    }


def _tcp_fields(
    handshake_s: Range, volume: dict[str, Any], rng: np.random.Generator
) -> dict[str, Any]:
    handshake = _between(rng, handshake_s)
    synack = round(handshake * _between(rng, _SYNACK_SHARE), _DECIMALS)
    ackdat = round(handshake - synack, _DECIMALS)
    return {
        "swin": _TCP_WINDOW,
        "dwin": _TCP_WINDOW,
        "stcpb": int(rng.integers(0, _TCP_SEQUENCE_LIMIT)),
        "dtcpb": int(rng.integers(0, _TCP_SEQUENCE_LIMIT)),
        "synack": synack,
        "ackdat": ackdat,
        "tcprtt": synack + ackdat,
        "sloss": volume["spkts"] // _PACKETS_PER_LOSS,
        "dloss": volume["dpkts"] // _PACKETS_PER_LOSS,
        "sjit": volume["sinpkt"] * _between(rng, _SOURCE_JITTER_FACTOR),
        "djit": volume["dinpkt"] * _between(rng, _DEST_JITTER_FACTOR),
    }


def _context_fields(profile: Profile, rng: np.random.Generator) -> dict[str, Any]:
    recent = ("ct_srv_src", "ct_dst_ltm", "ct_dst_src_ltm", "ct_src_ltm", "ct_srv_dst")
    same_port = ("ct_src_dport_ltm", "ct_dst_sport_ltm")
    return {
        "proto": profile.proto,
        "service": profile.service,
        "state": profile.state,
        "sttl": profile.source_ttl,
        "dttl": profile.dest_ttl,
        "ct_state_ttl": profile.ct_state_ttl,
        **{name: _whole(rng, profile.recent_connections) for name in recent},
        **{name: _whole(rng, profile.same_port_connections) for name in same_port},
    }


def _http_fields(volume: dict[str, Any], rng: np.random.Generator) -> dict[str, Any]:
    return {
        "trans_depth": 1,
        "ct_flw_http_mthd": 1,
        "response_body_len": int(volume["dbytes"] * _between(rng, _HTTP_BODY_SHARE)),
    }


def _sample(profile: Profile, rng: np.random.Generator) -> DemoFlow:
    volume = _volume_fields(profile, rng)
    fields = {
        **volume,
        **_context_fields(profile, rng),
        **(_tcp_fields(profile.handshake_s, volume, rng) if profile.handshake_s else {}),
        **(_http_fields(volume, rng) if profile.is_http else {}),
    }
    # Features a profile does not set (FTP counters, TCP fields of UDP flows) are zero.
    values = (fields.get(name, 0) for name in FEATURE_COLUMNS)
    features = {
        name: round(value, _DECIMALS) if isinstance(value, float) else value
        for name, value in zip(FEATURE_COLUMNS, values, strict=True)
    }
    return DemoFlow(profile=profile.name, features=features)


def generate_demo_flows(count: int, seed: int) -> list[DemoFlow]:
    """Draws `count` synthetic flows; the same count and seed give the same flows.

    Profiles take turns so each appears as soon as there is room, then the
    order is shuffled.
    """
    if not 1 <= count <= MAX_DEMO_FLOWS:
        raise ValueError(f"The flow count must be between 1 and {MAX_DEMO_FLOWS}, not {count}")
    if seed < 0:
        raise ValueError(f"The seed must be zero or greater, not {seed}")
    rng = np.random.default_rng(seed)
    flows = [_sample(PROFILES[index % len(PROFILES)], rng) for index in range(count)]
    return [flows[index] for index in rng.permutation(count)]


def build_demo_document(count: int, seed: int) -> dict[str, Any]:
    """A labelled document the scoring endpoint accepts as a request body.

    `profiles` names the profile each flow was drawn from, in the same order.
    """
    flows = generate_demo_flows(count, seed)
    return {
        "demo": True,
        "notice": DEMO_NOTICE,
        "seed": seed,
        "profiles": [flow.profile for flow in flows],
        "flows": [flow.features for flow in flows],
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Writes synthetic network flows for demo mode.")
    parser.add_argument("--count", type=int, default=DEFAULT_COUNT, help="flows to generate")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="repeat a previous run")
    parser.add_argument("--output", type=Path, help="file to write; prints to the screen if unset")
    args = parser.parse_args(argv)
    try:
        document = build_demo_document(args.count, args.seed)
    except ValueError as error:
        print(error)
        return 1
    text = json.dumps(document, indent=2)
    if args.output is None:
        print(text)
        return 0
    args.output.write_text(text + "\n", encoding="utf-8")
    print(f"Wrote {args.count} synthetic demo flows to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
